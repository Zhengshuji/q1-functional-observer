#!/usr/bin/env python3
"""Locate the defining file of every Paper I claim.

`CLAIMS.md` says which Lean declaration carries each paper item, but not *where* that declaration
lives.  This script closes that gap: for every declaration named in `CLAIMS.md` it finds the file and
line that defines it, and writes the result to `docs/PAPER_I_PROOF_MAP.md` between the generated
markers.

Design notes:
  * the source of truth is `CLAIMS.md` (itself generated) and the `.lean` files -- nothing is
    hand-maintained here;
  * only `theorem`/`def`/`abbrev`/`structure` lines are matched, so a name is never resolved to a
    mere use;
  * a declaration that cannot be located is reported as `MISSING` and makes the script exit
    non-zero, so CI can catch a stale index.

Usage:
    python scripts/paper_lean_index.py            # rewrite the generated block
    python scripts/paper_lean_index.py --check    # fail if the file is stale
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CLAIMS = ROOT / "Q1Paper" / "PaperI" / "S00_Interface" / "CLAIMS.md"
TARGET = ROOT / "docs" / "PAPER_I_PROOF_MAP.md"
BEGIN = "<!-- BEGIN GENERATED: claim -> declaration -> file -->"
END = "<!-- END GENERATED -->"

MODULE_TARGET = ROOT / "docs" / "PAPER_I_MODULE_MAP.md"
BEGINM = "<!-- BEGIN GENERATED: module -> purpose -->"
ENDM = "<!-- END GENERATED -->"

AUDIT_RE = re.compile(r"^#print axioms\s+([\w'.!?]+)")

DECL_RE = re.compile(r"^\s*(?:noncomputable\s+)?(?:theorem|def|abbrev|structure|lemma)\s+([\w'!?]+)")
CLAIM_ROW_RE = re.compile(r"^\|\s*\*\*(.+?)\*\*\s*\(`([^`]+)`\)\s*(?:—|-)\s*(.+?)\s*\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|")


def scan_declarations() -> dict[str, tuple[str, int]]:
    """Map every declaration name to (relative path, line number)."""
    found: dict[str, tuple[str, int]] = {}
    for pattern in ("Q1Paper/**/*.lean",):
        for path in sorted(ROOT.glob(pattern)):
            rel = path.relative_to(ROOT).as_posix()
            try:
                lines = path.read_text(encoding="utf-8").splitlines()
            except UnicodeDecodeError:
                continue
            for i, line in enumerate(lines, start=1):
                m = DECL_RE.match(line)
                if m:
                    found.setdefault(m.group(1), (rel, i))
    return found


def claim_rows() -> list[tuple[str, str, str, str, str]]:
    rows = []
    for line in CLAIMS.read_text(encoding="utf-8").splitlines():
        m = CLAIM_ROW_RE.match(line)
        if m:
            rows.append((m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)))
    return rows


def render(rows, decls) -> tuple[str, list[str]]:
    missing: list[str] = []
    out = [
        BEGIN,
        "",
        "Generated by `scripts/paper_lean_index.py` from `Q1Paper/PaperI/CLAIMS.md`; do not edit by hand.",
        "",
        "| paper item | label | Lean declaration | file : line | status |",
        "|---|---|---|---|---|",
    ]
    for item, label, desc, decl, status in rows:
        short = decl.rsplit(".", 1)[-1]
        loc = decls.get(short)
        if loc is None:
            missing.append(short)
            where = "**MISSING**"
        else:
            where = f"`{loc[0]}:{loc[1]}`"
        out.append(f"| {item} | `{label}` | `{decl}` | {where} | {status} |")
    out += ["", END]
    return "\n".join(out), missing


def audited_names() -> set[str]:
    path = ROOT / "Q1Paper" / "PaperI" / "Audit.lean"
    if not path.exists():
        return set()
    out: set[str] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        m = AUDIT_RE.match(line.strip())
        if m:
            out.add(m.group(1).rsplit(".", 1)[-1])
    return out


def docstring_head(path: pathlib.Path) -> str:
    """First substantive line of a module docstring, if any."""
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except UnicodeDecodeError:
        return ""
    inside = False
    fallback = ""
    for line in lines:
        stripped = line.strip()
        if not inside:
            if DECL_RE.match(line):
                return ""  # a declaration came first: no module-level docstring
            if stripped.startswith("/-!"):
                inside = True
                rest = stripped[3:].strip()
                if rest.endswith("-/"):
                    rest = rest[:-2].strip()
                if rest and not rest.startswith("-") and not rest.startswith("#"):
                    return rest
            continue
        if stripped.startswith("-/"):
            break
        if stripped.startswith("#") or not stripped:
            continue
        if DECL_RE.match(line) or stripped.startswith("/-"):
            continue  # a code sample or a nested docstring inside the module docstring
        if stripped.endswith("-/"):
            stripped = stripped[:-2].strip()
        if stripped:
            if len(stripped) >= 20 and stripped.endswith("."):
                return stripped  # a complete sentence: the module's stated purpose
            fallback = fallback or stripped
    return fallback


def render_modules(rows, decls) -> str:
    byfile: dict[str, list[str]] = {}
    for item, label, _desc, decl, _status in rows:
        loc = decls.get(decl.rsplit(".", 1)[-1])
        if loc:
            byfile.setdefault(loc[0], []).append(f"{item}")
    audited = audited_names()
    counts: dict[str, list[int]] = {}
    for path in sorted(ROOT.glob("Q1Paper/**/*.lean")):
        rel = path.relative_to(ROOT).as_posix()
        n = n_aud = 0
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except UnicodeDecodeError:
            continue
        for line in lines:
            m = DECL_RE.match(line)
            if m:
                n += 1
                if m.group(1) in audited:
                    n_aud += 1
        counts[rel] = [n, n_aud]

    out = [
        BEGINM,
        "",
        "Generated by `scripts/paper_lean_index.py`; do not edit by hand.",
        "",
        "Every Lean module in the tree, with the number of declarations it defines, how many of those",
        "are axiom-audited, which paper items it hosts (if any), and the first line of its own module",
        "docstring so a reader can see the author's stated purpose.",
        "",
        "| module | decls | audited | paper items | stated purpose |",
        "|---|---|---|---|---|",
    ]
    for rel in sorted(counts):
        n, n_aud = counts[rel]
        items = ", ".join(sorted(set(byfile.get(rel, [])))) or "—"
        head = docstring_head(ROOT / rel).replace("|", "\\|")[:110] or "**(no module docstring)**"
        out.append(f"| `{rel}` | {n} | {n_aud} | {items} | {head} |")
    out += ["", ENDM]
    return "\n".join(out)


def write_block(path: pathlib.Path, block: str, begin: str, end: str, title: str) -> None:
    current = path.read_text(encoding="utf-8") if path.exists() else f"# {title}\n\n{begin}\n{end}\n"
    if begin in current and end in current:
        head, _, rest = current.partition(begin)
        _, _, tail = rest.partition(end)
        current = head + block + tail
    else:
        current = current.rstrip() + "\n\n" + block + "\n"
    path.write_text(current, encoding="utf-8", newline="\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = claim_rows()
    if not rows:
        print("paper_lean_index: no rows parsed from CLAIMS.md", file=sys.stderr)
        return 1
    block, missing = render(rows, scan_declarations())
    modblock = render_modules(rows, scan_declarations())

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        currentm = MODULE_TARGET.read_text(encoding="utf-8") if MODULE_TARGET.exists() else ""
        ok = block in current and modblock in currentm and not missing
        print(f"paper_lean_index: {len(rows)} items, {len(missing)} unlocated")
        for name in missing:
            print(f"  unlocated: {name}", file=sys.stderr)
        if not ok:
            print("paper_lean_index: docs/PAPER_I_PROOF_MAP.md or docs/PAPER_I_MODULE_MAP.md is stale",
                  file=sys.stderr)
            return 1
        return 0

    write_block(TARGET, block, BEGIN, END, "Paper I: proof map")
    write_block(MODULE_TARGET, modblock, BEGINM, ENDM, "Paper I: module map")
    print(f"paper_lean_index: wrote {len(rows)} items, {len(missing)} unlocated")
    for name in missing:
        print(f"  unlocated: {name}", file=sys.stderr)
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
