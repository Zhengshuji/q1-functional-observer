#!/usr/bin/env python3
"""Locate the defining file of every Paper I claim.

`CLAIMS.md` says which Lean declaration carries each paper item, but not *where* that declaration
lives.  This script closes that gap: for every declaration named in `CLAIMS.md` it finds the file and
line that defines it, and writes the result to `docs/PAPER_I_PROOF_MAP.md` between the generated
markers.

Design notes:
  * the source of truth is `CLAIMS.md` (itself generated) and the `.lean` files -- nothing is
    hand-maintained here;
  * only `theorem`/`def`/`abbrev`/`structure` lines are matched, so a name is never resolved to a
    mere use;
  * a declaration that cannot be located is reported as `MISSING` and makes the script exit
    non-zero, so CI can catch a stale index.

Usage:
    python scripts/paper_lean_index.py            # rewrite the generated block
    python scripts/paper_lean_index.py --check    # fail if the file is stale
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CLAIMS = ROOT / "Q1Paper" / "PaperI" / "CLAIMS.md"
TARGET = ROOT / "docs" / "PAPER_I_PROOF_MAP.md"
BEGIN = "<!-- BEGIN GENERATED: claim -> declaration -> file -->"
END = "<!-- END GENERATED -->"

DECL_RE = re.compile(r"^\s*(?:noncomputable\s+)?(?:theorem|def|abbrev|structure|lemma)\s+([\w'!?]+)")
CLAIM_ROW_RE = re.compile(r"^\|\s*\*\*(.+?)\*\*\s*\(`([^`]+)`\)\s*(?:—|-)\s*(.+?)\s*\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|")


def scan_declarations() -> dict[str, tuple[str, int]]:
    """Map every declaration name to (relative path, line number)."""
    found: dict[str, tuple[str, int]] = {}
    for pattern in ("Q1Paper/**/*.lean",):
        for path in sorted(ROOT.glob(pattern)):
            rel = path.relative_to(ROOT).as_posix()
            try:
                lines = path.read_text(encoding="utf-8").splitlines()
            except UnicodeDecodeError:
                continue
            for i, line in enumerate(lines, start=1):
                m = DECL_RE.match(line)
                if m:
                    found.setdefault(m.group(1), (rel, i))
    return found


def claim_rows() -> list[tuple[str, str, str, str, str]]:
    rows = []
    for line in CLAIMS.read_text(encoding="utf-8").splitlines():
        m = CLAIM_ROW_RE.match(line)
        if m:
            rows.append((m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)))
    return rows


def render(rows, decls) -> tuple[str, list[str]]:
    missing: list[str] = []
    out = [
        BEGIN,
        "",
        "Generated by `scripts/paper_lean_index.py` from `Q1Paper/PaperI/CLAIMS.md`; do not edit by hand.",
        "",
        "| paper item | label | Lean declaration | file : line | status |",
        "|---|---|---|---|---|",
    ]
    for item, label, desc, decl, status in rows:
        short = decl.rsplit(".", 1)[-1]
        loc = decls.get(short)
        if loc is None:
            missing.append(short)
            where = "**MISSING**"
        else:
            where = f"`{loc[0]}:{loc[1]}`"
        out.append(f"| {item} | `{label}` | `{decl}` | {where} | {status} |")
    out += ["", END]
    return "\n".join(out), missing


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = claim_rows()
    if not rows:
        print("paper_lean_index: no rows parsed from CLAIMS.md", file=sys.stderr)
        return 1
    block, missing = render(rows, scan_declarations())

    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        ok = block in current and not missing
        print(f"paper_lean_index: {len(rows)} items, {len(missing)} unlocated")
        for name in missing:
            print(f"  unlocated: {name}", file=sys.stderr)
        if not ok:
            print("paper_lean_index: docs/PAPER_I_PROOF_MAP.md is stale", file=sys.stderr)
            return 1
        return 0

    if TARGET.exists():
        current = TARGET.read_text(encoding="utf-8")
    else:
        current = "# Paper I: proof map\n\n" + BEGIN + "\n" + END + "\n"
    if BEGIN in current and END in current:
        head, _, rest = current.partition(BEGIN)
        _, _, tail = rest.partition(END)
        current = head + block + tail
    else:
        current = current.rstrip() + "\n\n" + block + "\n"
    TARGET.write_text(current, encoding="utf-8", newline="\n")
    print(f"paper_lean_index: wrote {len(rows)} items, {len(missing)} unlocated")
    for name in missing:
        print(f"  unlocated: {name}", file=sys.stderr)
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
