"""generate_paperI_modules.py -- a generated index of the Lean modules.

The repository has ~70 `.lean` files under `Q1Paper/PaperI/` plus ~38 at `Q1Paper/`, with names
accumulated over the project's history.  Rather than renaming or merging them (which would churn
every import and put the 416-declaration axiom audit at risk), this script generates a **module
index** that states, for every file, what it proves and which paper item it serves.

The index is generated, so it cannot drift: CI runs `--check` and fails when it is stale.

    python scripts/generate_paperI_modules.py           # regenerate
    python scripts/generate_paperI_modules.py --check   # fail if stale (CI)

Each row is derived from the file itself: the header comment block's first meaningful sentence,
the declared `theorem`/`def` count, and the first few declaration names.  The *responsibility*
column is the one thing a script cannot infer, so whatever is written in the file's own header is
quoted verbatim -- that keeps the index honest rather than inventive.
"""

from __future__ import annotations

import io
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIRS = [
    ("Q1Paper/PaperI", "Paper I modules (`namespace Q1Paper.PaperI.*`)"),
    ("Q1Paper", "Root modules (`namespace Q1Paper.*`)"),
]

DECL = re.compile(r"^(?:noncomputable\s+)?(?:private\s+)?(theorem|lemma|def|abbrev|structure|instance)\s+(\w+)", re.M)


def header_summary(text: str) -> str:
    """First meaningful sentence of the file's leading comment block."""
    m = re.match(r"\s*/-(.*?)-/", text, re.S)
    if not m:
        return ""
    body = m.group(1)
    for line in body.splitlines():
        line = line.strip().lstrip("*-").strip()
        if not line or line.startswith("Q1Paper/") or set(line) <= set("-=*"):
            continue
        if len(line) < 12:
            continue
        return line
    return ""


def rows_for(rel: str):
    out = []
    d = os.path.join(REPO, rel)
    if not os.path.isdir(d):
        return out
    for name in sorted(os.listdir(d)):
        if not name.endswith(".lean"):
            continue
        path = os.path.join(d, name)
        text = io.open(path, encoding="utf-8").read()
        decls = DECL.findall(text)
        n_thm = sum(1 for k, _ in decls if k in ("theorem", "lemma"))
        n_def = sum(1 for k, _ in decls if k in ("def", "abbrev", "structure", "instance"))
        sample = ", ".join("`%s`" % n for _, n in decls[:4])
        if len(decls) > 4:
            sample += ", …"
        summary = header_summary(text)
        out.append((name, n_thm, n_def, sample, summary))
    return out


def render() -> str:
    parts = [
        "# Lean module index (generated)\n",
        "Generated by `scripts/generate_paperI_modules.py`; do not edit by hand.\n",
        "The purpose of this file is *orientation*: which file proves what, and how many\n",
        "declarations it contributes.  It deliberately does **not** rename or merge anything.\n",
        "\n",
        "The four entry points and their separate jobs:\n",
        "\n",
        "| file | job |\n",
        "|---|---|\n",
        "| `MainTheorems.lean` | what Lean must load (the implementation) |\n",
        "| `Claims.lean` | what the paper claims and where it is proved (narrative) |\n",
        "| `ClaimsCheck.lean` | machine-checked index: one `#check` per paper item |\n",
        "| `Audit.lean` | the axiom footprint of every audited declaration |\n",
        "\n",
    ]
    for rel, title in DIRS:
        rows = rows_for(rel)
        if not rows:
            continue
        parts.append(f"## `{rel}/` — {title}\n\n")
        parts.append(f"{len(rows)} files, "
                     f"{sum(r[1] for r in rows)} theorems, "
                     f"{sum(r[2] for r in rows)} definitions/structures.\n\n")
        parts.append("| file | thm | def | first declarations | header summary |\n")
        parts.append("|---|---:|---:|---|---|\n")
        for name, n_thm, n_def, sample, summary in rows:
            s = summary.replace("|", "\\|")
            if len(s) > 110:
                s = s[:107] + "…"
            parts.append(f"| `{name}` | {n_thm} | {n_def} | {sample} | {s} |\n")
        parts.append("\n")
    return "".join(parts)


def main(argv):
    check = "--check" in argv
    targets = {
        os.path.join(REPO, "Q1Paper", "PaperI", "MODULES.md"): render(),
    }
    stale = []
    for path, content in targets.items():
        if check:
            current = io.open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if current != content:
                stale.append(os.path.relpath(path, REPO))
        else:
            io.open(path, "w", encoding="utf-8", newline="\n").write(content)
            print("wrote", os.path.relpath(path, REPO))
    if check:
        if stale:
            print("stale (regenerate with scripts/generate_paperI_modules.py):", file=sys.stderr)
            for s in stale:
                print("  " + s, file=sys.stderr)
            return 1
        print("module index up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
