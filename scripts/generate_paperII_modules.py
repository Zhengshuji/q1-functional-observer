"""generate_paperII_modules.py -- a generated index of the Paper II Lean modules.

Paper II's tree is small (`Q1Paper/PaperII/`, one level, plus `Read/`), so instead of the
Paper I script's directory walk this one reads every file in the directory, quotes the first
sentence of its header, and counts the declarations it contributes.  The Möbius of the reading
order lives in `Q1Paper/PaperII/Read/`, which this index points at.

The index is generated, so it cannot drift: CI runs `--check` and fails when it is stale.

    python scripts/generate_paperII_modules.py           # regenerate
    python scripts/generate_paperII_modules.py --check   # fail if stale (CI)
"""

from __future__ import annotations

import io
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(REPO, "Q1Paper", "PaperII")
OUT = os.path.join(DIR, "MODULES.md")

DECL = re.compile(
    r"^(?:noncomputable\s+)?(?:private\s+)?(theorem|lemma|def|abbrev|structure|instance)\s+(\w+)",
    re.M,
)

SKIP = {"Audit.lean", "Claims.lean", "ClaimsCheck.lean", "MainTheorems.lean"}


def header_summary(text: str) -> str:
    m = re.match(r"\s*/-(.*?)-/", text, re.S)
    if not m:
        return ""
    for line in m.group(1).splitlines():
        line = line.strip().lstrip("*-").strip()
        if not line or line.startswith("Q1Paper/") or set(line) <= set("-=*"):
            continue
        if len(line) < 12:
            continue
        return line
    return ""


def rows():
    out = []
    for name in sorted(os.listdir(DIR)):
        if not name.endswith(".lean") or name in SKIP:
            continue
        path = os.path.join(DIR, name)
        text = io.open(path, encoding="utf-8").read()
        decls = DECL.findall(text)
        n_thm = sum(1 for k, _ in decls if k in ("theorem", "lemma"))
        n_def = len(decls) - n_thm
        first = ", ".join("`" + d + "`" for _, d in decls[:3])
        out.append((name, n_thm, n_def, first, header_summary(text)))
    return out


def render() -> str:
    lines = [
        "# Paper II: Lean module index (generated)",
        "",
        "Generated by `scripts/generate_paperII_modules.py`; do not edit by hand.  The purpose",
        "of this file is *orientation*: which file proves what, and how many declarations it",
        "contributes.  It deliberately does **not** rename or merge anything.",
        "",
        "The entry points and their separate jobs:",
        "",
        "| file | job |",
        "|---|---|",
        "| `MainTheorems.lean` | what Lean must load (the implementation) |",
        "| `Claims.lean` | what the paper claims and where it is proved (narrative) |",
        "| `ClaimsCheck.lean` | machine-checked index: one `#check` per paper item |",
        "| `CLAIMS.md` | the same table for readers who do not know Lean (generated) |",
        "| `Audit.lean` | the axiom footprint of every audited declaration |",
        "| `Read/All.lean` | the reading entry: the paper's order, one `#check` per step |",
        "",
        "## `Q1Paper/PaperII/` -- the development",
        "",
        "| file | thm | def | first declarations | header summary |",
        "|---|---:|---:|---|---|",
    ]
    for name, n_thm, n_def, first, summary in rows():
        lines.append(f"| `{name}` | {n_thm} | {n_def} | {first} | {summary} |")
    lines += [
        "",
        "## `Q1Paper/PaperII/Read/` -- the reading order",
        "",
        "| file | paper section |",
        "|---|---|",
        "| `S01_Standing.lean` | standing results (Paper I) and the interface |",
        "| `S02_Sandwich.lean` | sandwich, monotonicity, saturation |",
        "| `S03_MinOrder.lean` | the minimum order (complex designs) |",
        "| `S04_LowerBound.lean` | the spectral lower bound |",
        "| `S05_Tightness.lean` | tightness (Proposition 3) |",
        "| `S06_RealDesigns.lean` | the real-design specification `DECℂ` |",
        "| `All.lean` | all of the above |",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    rendered = render()
    if "--check" in sys.argv:
        if not os.path.exists(OUT):
            print("missing", OUT)
            return 1
        current = io.open(OUT, encoding="utf-8").read()
        if current != rendered:
            print("stale:", OUT)
            return 1
        print("paper II module index up to date")
        return 0
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(rendered)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
